import fs from "node:fs";
import path from "node:path";

/**
 * Phase stats for T20 internationals: what each player did in the powerplay (overs 1-6), the
 * middle overs (7-15) and at the death (16-20), from Cricsheet ball-by-ball data.
 *
 *   npx tsx src/etl/phase-stats.ts [data/raw/t20s_json] [data/phase-stats.sql]
 *
 * Writes one row per player: a JSON array per phase,
 *   [bat_runs, bat_balls, bat_outs, bowl_balls, bowl_runs, bowl_wkts]
 * Ids are the same `crick_<cricsheet id>` as data/seed.sql. Run by .github/workflows/phase-stats.yml
 * (cricsheet.org is not reachable from every environment).
 */

type Phase = "pp" | "mid" | "death";
type Line = [number, number, number, number, number, number];

const PHASE_OF = (over: number): Phase => (over < 6 ? "pp" : over < 15 ? "mid" : "death");
/** Dismissals credited to the bowler. */
const BOWLER_WICKETS = new Set(["bowled", "caught", "caught and bowled", "lbw", "stumped", "hit wicket"]);
/** Players with fewer T20I appearances are left out (the game's pool never reaches them). */
const MIN_MATCHES = 8;

function main() {
  const dir = path.resolve(process.argv[2] ?? "data/raw/t20s_json");
  const out = path.resolve(process.argv[3] ?? "data/phase-stats.sql");
  if (!fs.existsSync(dir)) {
    console.error(`[phase] Missing ${dir}. Download https://cricsheet.org/downloads/t20s_json.zip and unzip it there.`);
    process.exit(1);
  }

  const stats = new Map<string, Record<Phase, Line>>();
  const matches = new Map<string, number>();
  const get = (id: string) => {
    let s = stats.get(id);
    if (!s) stats.set(id, (s = { pp: [0, 0, 0, 0, 0, 0], mid: [0, 0, 0, 0, 0, 0], death: [0, 0, 0, 0, 0, 0] }));
    return s;
  };

  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json"));
  let used = 0;
  for (const file of files) {
    let match: any;
    try {
      match = JSON.parse(fs.readFileSync(path.join(dir, file), "utf-8"));
    } catch {
      continue;
    }
    const info = match.info ?? {};
    if (info.gender !== "male" || !info.registry?.people) continue;
    // Full 20-over internationals only: shortened matches distort the phases
    if (info.overs && info.overs !== 20) continue;
    const people: Record<string, string> = info.registry.people;
    for (const names of Object.values(info.players ?? {}) as string[][]) {
      for (const n of names) if (people[n]) matches.set(people[n], (matches.get(people[n]) ?? 0) + 1);
    }
    for (const inn of match.innings ?? []) {
      if (inn.super_over) continue;
      for (const o of inn.overs ?? []) {
        const phase = PHASE_OF(o.over);
        for (const d of o.deliveries ?? []) {
          const ex = d.extras ?? {};
          const batter = people[d.batter];
          const bowler = people[d.bowler];
          if (batter && !ex.wides) {
            const b = get(batter)[phase];
            b[0] += d.runs?.batter ?? 0;
            b[1] += 1;
          }
          for (const w of d.wickets ?? []) {
            const out = people[w.player_out];
            if (out) get(out)[phase][2] += 1;
            if (bowler && BOWLER_WICKETS.has(w.kind)) get(bowler)[phase][5] += 1;
          }
          if (bowler) {
            const b = get(bowler)[phase];
            if (!ex.wides && !ex.noballs) b[3] += 1;
            b[4] += (d.runs?.batter ?? 0) + (ex.wides ?? 0) + (ex.noballs ?? 0);
          }
        }
      }
    }
    used++;
  }

  const rows = [...stats.entries()]
    .filter(([id]) => (matches.get(id) ?? 0) >= MIN_MATCHES)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, s]) => `('crick_${id}', 'T20', '${JSON.stringify(s)}')`);

  const sql = [
    "-- Generated by src/etl/phase-stats.ts from Cricsheet T20I ball-by-ball data. Do not edit.",
    `-- ${used} matches, ${rows.length} players with ${MIN_MATCHES}+ appearances. Safe to run more than once.`,
    "-- Each phase: [bat_runs, bat_balls, bat_outs, bowl_balls, bowl_runs, bowl_wkts]; pp = overs 1-6, mid = 7-15, death = 16-20.",
    "CREATE TABLE IF NOT EXISTS player_phase_stats (",
    "    player_id TEXT NOT NULL,",
    "    format TEXT NOT NULL,",
    "    phases TEXT NOT NULL,",
    "    PRIMARY KEY (player_id, format)",
    ");",
    "DELETE FROM player_phase_stats WHERE format = 'T20';",
    // Batches of 200 rows keep each statement well inside D1's limits
    ...Array.from({ length: Math.ceil(rows.length / 200) }, (_, i) =>
      `INSERT OR REPLACE INTO player_phase_stats (player_id, format, phases) VALUES\n${rows.slice(i * 200, i * 200 + 200).join(",\n")};`
    ),
    "",
  ].join("\n");
  fs.writeFileSync(out, sql);
  console.log(`[phase] ${used} matches, ${rows.length} players -> ${out}`);
}

main();
