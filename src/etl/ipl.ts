import fs from "node:fs";
import path from "node:path";
import { LeagueAccumulator, categoryGuess, normsOf, roleOf, statsOf, strongSpin, type PlayerAgg } from "./league";
import { COUNTRY_MAP } from "./countries";
import { iplGroundOf } from "../core/ipl-grounds";

/**
 * The IPL, from Cricsheet ball-by-ball data, for the game's IPL mode.
 *
 *   npx tsx src/etl/ipl.ts [data/raw]
 *
 * Reads data/raw/ipl_json (and, for each player's country, the international files if present) and writes
 *   data/ipl.sql                          IPL stats, roles, phases and splits (format 'IPL'); new players are added
 *   src/core/data-norms-ipl.generated.ts  the league's norms, par scores and seasons
 *   data/ipl-report.md                    what was read, who leads, and how well the pace/spin guess matches known players
 * Run by .github/workflows/ipl.yml. Safe to run more than once.
 */

const RAW = path.resolve(process.argv[2] ?? "data/raw");
const MIN_MATCHES = 10;
const dir = path.join(RAW, "ipl_json");
if (!fs.existsSync(dir)) {
  console.error(`[ipl] Missing ${dir}: download https://cricsheet.org/downloads/ipl_json.zip and unzip it there.`);
  process.exit(1);
}

// ---- The league ---------------------------------------------------------------------------------
const acc = new LeagueAccumulator();
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json"));
let used = 0;
for (const f of files) {
  try {
    if (acc.addMatch(JSON.parse(fs.readFileSync(path.join(dir, f), "utf-8")), iplGroundOf)) used++;
  } catch {
    // skip malformed match files
  }
}
console.log(`[ipl] ${used} of ${files.length} matches read, ${acc.players.size} players`);

// ---- Countries, from the international files: the side a player represented most --------------------
const teamCounts = new Map<string, Map<string, number>>();
/** Every team name in the international files, to see which ones the country table does not cover */
const teamsSeen = new Map<string, number>();
for (const d of ["t20s_json", "odis_json", "tests_json"]) {
  const p = path.join(RAW, d);
  if (!fs.existsSync(p)) continue;
  for (const f of fs.readdirSync(p).filter((x) => x.endsWith(".json"))) {
    try {
      const info = JSON.parse(fs.readFileSync(path.join(p, f), "utf-8")).info ?? {};
      if (info.gender !== "male" || !info.registry?.people) continue;
      for (const [team, names] of Object.entries(info.players ?? {}) as [string, string[]][]) {
        teamsSeen.set(team, (teamsSeen.get(team) ?? 0) + 1);
        if (!COUNTRY_MAP[team]) continue;
        for (const n of names) {
          const id = info.registry.people[n];
          if (!id) continue;
          const m = teamCounts.get(id) ?? new Map<string, number>();
          m.set(team, (m.get(team) ?? 0) + 1);
          teamCounts.set(id, m);
        }
      }
    } catch {
      // skip
    }
  }
}
/**
 * Overseas players the international files do not place (a country the table lacks, or a player who
 * has only played franchise cricket), by the name Cricsheet gives them in the IPL files.
 */
const KNOWN_ABROAD: Record<string, string> = {
  "Rashid Khan": "AFG", "Noor Ahmad": "AFG", "Mohammad Nabi": "AFG", "Mujeeb Ur Rahman": "AFG", "Naveen-ul-Haq": "AFG",
  "Fazalhaq Farooqi": "AFG", "Rahmanullah Gurbaz": "AFG", "Azmatullah Omarzai": "AFG", "AM Ghazanfar": "AFG",
  "KK Cooper": "WI",
};
const countryOf = (id: string, name = ""): string | undefined => {
  const m = teamCounts.get(id);
  if (!m) return KNOWN_ABROAD[name];
  const top = [...m].sort((a, b) => b[1] - a[1])[0][0];
  return COUNTRY_MAP[top];
};

// ---- Players the game already has (to leave them alone), from the seed ---------------------------------
const known = new Map<string, { country: string; category: string; role: string; name: string }>();
const seedPath = path.resolve("data/seed.sql");
if (fs.existsSync(seedPath)) {
  const re = /VALUES \('crick_([0-9a-f]+)', '[^']*', '((?:[^']|'')*)', '([A-Za-z:]+)', '(?:LHB|RHB)', '(NONE|PACE|SPIN)', '(?:[^']|'')*', '(BAT|WK|AR|BOWL)'\)/;
  for (const line of fs.readFileSync(seedPath, "utf-8").split("\n")) {
    if (!line.startsWith("INSERT OR REPLACE INTO players")) continue;
    const m = re.exec(line);
    if (m) known.set(m[1], { name: m[2].replace(/''/g, "'"), country: m[3], category: m[4], role: m[5] });
  }
}
console.log(`[ipl] ${known.size} players already in the game; ${teamCounts.size} players with an international record`);

// ---- SQL ----------------------------------------------------------------------------------------------
const esc = (s: string) => s.replace(/'/g, "''");
const eligible = [...acc.players.values()].filter((p) => p.matches >= MIN_MATCHES).sort((a, b) => a.id.localeCompare(b.id));
const sql: string[] = [
  "-- Generated by src/etl/ipl.ts from Cricsheet IPL ball-by-ball data. Do not edit. Safe to run more than once.",
  "-- Players new to the game are added (INSERT OR IGNORE: existing ones keep their details); everything else is format 'IPL'.",
  "CREATE TABLE IF NOT EXISTS player_phase_stats (player_id TEXT NOT NULL, format TEXT NOT NULL, phases TEXT NOT NULL, PRIMARY KEY (player_id, format));",
  "CREATE TABLE IF NOT EXISTS player_splits (player_id TEXT NOT NULL, format TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY (player_id, format));",
  "DELETE FROM player_format_stats WHERE format = 'IPL';",
  "DELETE FROM player_format_roles WHERE format = 'IPL';",
  "DELETE FROM player_phase_stats WHERE format = 'IPL';",
  "DELETE FROM player_splits WHERE format = 'IPL';",
];
const added: { p: PlayerAgg; country: string; role: string; category: string }[] = [];
const roleRows: { id: string; role: string; category: string; force?: string }[] = [];
for (const p of eligible) {
  const role = roleOf(p);
  const guess = categoryGuess(p);
  const k = known.get(p.id);
  const bowls = role === "BOWL" || role === "AR";
  if (!k) {
    const country = countryOf(p.id, p.name) ?? "IND";
    const category = bowls ? (guess === "NONE" ? "PACE" : guess) : "NONE";
    added.push({ p, country, role, category });
    sql.push(
      `INSERT OR IGNORE INTO players (id, cricinfo_id, name, short_name, country, batting_hand, bowling_category, bowling_style, primary_role) VALUES ('crick_${p.id}', '', '${esc(p.name)}', '${esc(p.name)}', '${country}', 'RHB', '${category}', '${category === "SPIN" ? "Off break" : category === "PACE" ? "Right-arm fast-medium" : ""}', '${role}');`
    );
  }
  // A known "pace" bowler whose wickets are full of stumpings is a spinner the game has down wrong (Kumble, Kartik, Chawla)
  const fix = bowls && k && k.category === "PACE" && strongSpin(p) ? "SPIN" : undefined;
  roleRows.push({ id: p.id, role, category: bowls ? guess : "NONE", ...(fix ? { force: fix } : {}) });
}
const batches = (rows: string[], head: string) =>
  Array.from({ length: Math.ceil(rows.length / 150) }, (_, i) => `${head} VALUES\n${rows.slice(i * 150, i * 150 + 150).join(",\n")};`);
const s = (p: PlayerAgg) => statsOf(p);
sql.push(
  ...batches(
    eligible.map((p) => {
      const t = s(p);
      return `('crick_${p.id}', 'IPL', ${t.matches}, ${t.bat_innings}, ${t.bat_runs}, ${t.bat_balls}, ${t.bat_average}, ${t.bat_strike_rate}, ${t.top_order_innings}, ${t.middle_order_innings}, ${t.finisher_innings}, ${t.bowl_innings}, ${t.bowl_overs}, ${t.bowl_wickets}, ${t.bowl_runs_conceded}, ${t.bowl_average}, ${t.bowl_economy})`;
    }),
    "INSERT OR REPLACE INTO player_format_stats (player_id, format, matches, bat_innings, bat_runs, bat_balls, bat_average, bat_strike_rate, top_order_innings, middle_order_innings, finisher_innings, bowl_innings, bowl_overs, bowl_wickets, bowl_runs_conceded, bowl_average, bowl_economy)"
  )
);
// A player's IPL role; his bowling type is the one the game already has for him (a guess from his overs when it has none)
for (const r of roleRows) {
  const batter = r.role === "BAT" || r.role === "WK";
  sql.push(
    batter
      ? `INSERT OR REPLACE INTO player_format_roles (player_id, format, primary_role, bowling_category) VALUES ('crick_${r.id}', 'IPL', '${r.role}', 'NONE');`
      : r.force
        ? `INSERT OR REPLACE INTO player_format_roles (player_id, format, primary_role, bowling_category) VALUES ('crick_${r.id}', 'IPL', '${r.role}', '${r.force}');`
        : `INSERT OR REPLACE INTO player_format_roles (player_id, format, primary_role, bowling_category) SELECT id, 'IPL', '${r.role}', CASE WHEN bowling_category = 'NONE' THEN '${r.category === "NONE" ? "PACE" : r.category}' ELSE bowling_category END FROM players WHERE id = 'crick_${r.id}';`
  );
}
sql.push(
  ...batches(
    eligible.map((p) => `('crick_${p.id}', 'IPL', '${JSON.stringify({ pp: p.phase.pp, mid: p.phase.mid, death: p.phase.death })}')`),
    "INSERT OR REPLACE INTO player_phase_stats (player_id, format, phases)"
  ),
  ...batches(
    eligible.map((p) => `('crick_${p.id}', 'IPL', '${esc(JSON.stringify({ pos: p.pos, chase: p.chase }))}')`),
    "INSERT OR REPLACE INTO player_splits (player_id, format, data)"
  ),
  ""
);
fs.writeFileSync(path.resolve("data/ipl.sql"), sql.join("\n"));

// ---- Norms ---------------------------------------------------------------------------------------------
const norms = normsOf(acc, MIN_MATCHES);
fs.writeFileSync(
  path.resolve("src/core/data-norms-ipl.generated.ts"),
  `// Generated by src/etl/ipl.ts from Cricsheet IPL ball-by-ball data. Do not edit.
// The league's own norms in the shape of data-norms.generated.ts (sr = strike rate, bpo = balls per dismissal,
// econ = runs per over, bpw = balls per wicket), real first-innings par scores at the IPL grounds, and each
// player's middle season (for the era adjustment).
export const IPL_NORMS = ${JSON.stringify(norms, null, 2)} as const;
`
);

// ---- Report --------------------------------------------------------------------------------------------
const md: string[] = ["# IPL data: report", ""];
md.push(`Read ${used} of ${files.length} Cricsheet IPL matches (men's, full 20 overs): ${acc.players.size} players, ${eligible.length} with ${MIN_MATCHES}+ matches. Seasons ${Object.keys(acc.norms.era).sort().join(", ")} (three-year buckets).`, "");
md.push(`League: first innings ${norms.innings[0]?.runs} in ${norms.innings[0]?.overs} overs, chasing ${norms.innings[1]?.runs}; batting first wins ${((norms.results.batFirstWins / Math.max(1, norms.results.decisive)) * 100).toFixed(1)}% of ${norms.results.decisive} decided matches. Par (all grounds) ${norms.par.all}.`, "");
md.push("| Phase | Strike rate | Balls per dismissal | Economy |", "|---|---|---|---|");
for (const k of ["pp", "mid", "death"] as const) md.push(`| ${k} | ${norms.phase[k].sr} | ${norms.phase[k].bpo} | ${norms.phase[k].econ} |`);
md.push("", "| Ground | First-innings par | Matches |", "|---|---|---|");
for (const [g, v] of Object.entries(norms.par.ground)) md.push(`| ${g} | ${v.avg} | ${v.n} |`);
md.push("", "| Season bucket | Strike rate | Average | Economy |", "|---|---|---|---|");
for (const [k, v] of Object.entries(norms.era)) md.push(`| ${k} | ${v.sr} | ${v.avg} | ${v.econ} |`);
const top = (f: (p: PlayerAgg) => number, n = 12) => [...eligible].sort((a, b) => f(b) - f(a)).slice(0, n);
const perClub: Record<string, number> = {};
const perClub20: Record<string, number> = {};
for (const p of eligible) for (const c of norms.franchises[`crick_${p.id}`] ?? []) {
  perClub[c] = (perClub[c] ?? 0) + 1;
  if (p.matches >= 20) perClub20[c] = (perClub20[c] ?? 0) + 1;
}
md.push("", "## Players by franchise (5+ matches for the club; the second number also has 20+ IPL matches, the draft pool's bar)", "", ...Object.keys(perClub).sort().map((c) => `- ${c}: ${perClub[c]} (${perClub20[c] ?? 0})`));
md.push("", "## Most runs", "", ...top((p) => p.batRuns).map((p) => `- ${p.name} (${p.id}): ${p.batRuns} runs, avg ${statsOf(p).bat_average}, SR ${statsOf(p).bat_strike_rate}, ${p.matches} matches`));
md.push("", "## Most wickets", "", ...top((p) => p.bowlWkts).map((p) => `- ${p.name} (${p.id}): ${p.bowlWkts} wickets, econ ${statsOf(p).bowl_economy}, ${p.matches} matches`));

// How good is the pace/spin guess? Against players whose style the game already knows
let right = 0, wrong = 0;
const misses: string[] = [];
for (const p of eligible) {
  const k = known.get(p.id);
  if (!k || (k.category !== "PACE" && k.category !== "SPIN") || p.bowlBalls < 300) continue;
  const g = categoryGuess(p);
  if (g === k.category) right++;
  else (wrong++, misses.length < 25 && misses.push(`${k.name}: game ${k.category}, guess ${g}`));
}
md.push("", "## The pace/spin guess (used only for players new to the game)", "", `Against ${right + wrong} known bowlers with 300+ IPL balls: ${right} right, ${wrong} wrong (${((right / Math.max(1, right + wrong)) * 100).toFixed(1)}% right).`, "", ...misses.map((m) => `- ${m}`));
const byCountry: Record<string, number> = {};
for (const a of added) byCountry[a.country] = (byCountry[a.country] ?? 0) + 1;
const guessedIndian = added.filter((a) => a.country === "IND" && !teamCounts.has(a.p.id)).length;
md.push("", "## Teams in the international files", "", ...[...teamsSeen].sort((a, b) => b[1] - a[1]).slice(0, 45).map(([t, n]) => `- ${t}: ${n} matches${COUNTRY_MAP[t] ? "" : " (not in the country table)"}`));
md.push("", `Players placed by name (not in the international files): ${added.filter((a) => a.country !== "IND" && !teamCounts.has(a.p.id)).map((a) => `${a.p.name} ${a.country}`).join(", ") || "none"}.`);
md.push("", "## Players new to the game", "", `${added.length} added (${eligible.length - added.length} already there). By country: ${Object.entries(byCountry).map(([c, n]) => `${c} ${n}`).join(", ")}. ${guessedIndian} are Indian only because they have no international record (a few may be overseas players).`);
md.push("", "Roles of the added players: " + ["BAT", "WK", "AR", "BOWL"].map((r) => `${r} ${added.filter((a) => a.role === r).length}`).join(", ") + ".");
const overseasNoIntl = added.filter((a) => a.country === "IND" && !teamCounts.has(a.p.id)).sort((a, b) => b.p.matches - a.p.matches).slice(0, 25).map((a) => `${a.p.name} (${a.p.matches})`);
md.push("", "Most-capped of those (check for overseas players among them): " + overseasNoIntl.join(", "));
fs.writeFileSync(path.resolve("data/ipl-report.md"), md.join("\n") + "\n");
console.log(`[ipl] wrote data/ipl.sql (${eligible.length} players, ${added.length} new), norms and report`);
